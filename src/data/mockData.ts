export function parseEgyptianNationalId(id: string) {
  if (!id || id.length !== 14 || !/^\d{14}$/.test(id)) {
    return null;
  }
  const century = id[0] === '2' ? 1900 : id[0] === '3' ? 2000 : null;
  if (!century) return null;

  const year = century + parseInt(id.substring(1, 3), 10);
  const month = parseInt(id.substring(3, 5), 10);
  const day = parseInt(id.substring(5, 7), 10);
  const govCode = id.substring(7, 9);
  const governorate = EGYPTIAN_GOVERNORATES[govCode] || 'Unknown Governorate';
  const serialGenderDigit = parseInt(id[12], 10);
  const gender: 'male' | 'female' = serialGenderDigit % 2 !== 0 ? 'male' : 'female';
  const age = new Date().getFullYear() - year;

  return {
    valid: true,
    birthDate: `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`,
    governorate,
    govCode,
    gender,
    age,
  };
}

